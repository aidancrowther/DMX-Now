"""Virtual serial backend contract."""

from __future__ import annotations

from typing import Protocol


class VirtualSerialBackend(Protocol):
    @property
    def path(self) -> str: ...
    @property
    def client_connected(self) -> bool: ...
    def start(self) -> None: ...
    def read(self, size: int = 4096) -> bytes: ...
    def stop(self) -> None: ...